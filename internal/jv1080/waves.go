// WaveSource is one selectable wave group of a tone: the wave group
// (0 = INT, 1 = PCM card, 2 = EXP) and the wave group ID (for INT:
// 1 = INT-A, 2 = INT-B; for EXP: the expansion board number 1-4 = A-D,
// per doc/patch-edit-mode-structure.md).
type WaveSource struct {
	Label   string // display label, e.g. "INT-A"
	Group   int    // wave group (tone offset 0x01): 0 = INT, 2 = EXP
	GroupID int    // wave group ID (tone offset 0x02)
}

// WaveSources are the six wave sources selectable on the patch editor:
// the two internal groups and the four expansion boards.
var WaveSources = [6]WaveSource{
	{Label: "INT-A", Group: 0, GroupID: 1},
	{Label: "INT-B", Group: 0, GroupID: 2},
	{Label: "EXP-A", Group: 2, GroupID: 1},
	{Label: "EXP-B", Group: 2, GroupID: 2},
	{Label: "EXP-C", Group: 2, GroupID: 3},
	{Label: "EXP-D", Group: 2, GroupID: 4},
}

// WaveSourceIndex returns the index of the wave source with the given
// group and group ID, or -1 if it is not one of the six selectable
// sources (e.g. a PCM card group).
func WaveSourceIndex(group, groupID int) int {
	for i, s := range WaveSources {
		if s.Group == group && s.GroupID == groupID {
			return i
		}
	}
	return -1
}

// WaveSourceAt returns the wave source at index i (0-5).
func WaveSourceAt(i int) WaveSource { return WaveSources[i] }

// WaveCount returns the number of waves in the wave group: 255 for the
// internal groups and the expansion boards, 193 for INT-B.
func WaveCount(group, groupID int) int {
	if group == 0 && groupID == 2 {
		return len(waveNamesIntB)
	}
	return 255
}

// WaveName returns the factory name of a wave (number 1-255) in the
// given wave group. The second return value is false when the group has
// no documented names (PCM card, EXP boards) or the number is out of
// range.
func WaveName(group, groupID, number int) (string, bool) {
	var names []string
	switch {
	case group == 0 && groupID == 1:
		names = waveNamesIntA
	case group == 0 && groupID == 2:
		names = waveNamesIntB
	default:
		return "", false
	}
	if number < 1 || number > len(names) {
		return "", false
	}
	return names[number-1], true
}

// WaveOptions returns the dropdown entries for a wave group: one entry
// per wave, "001 Ac Piano1 A" style with the zero-padded wave number
// followed by the factory name (number only for groups without
// documented names, e.g. the EXP boards).
func WaveOptions(group, groupID int) []string {
	count := WaveCount(group, groupID)
	opts := make([]string, count)
	for i := 1; i <= count; i++ {
		num := fmt.Sprintf("%03d", i)
		if name, ok := WaveName(group, groupID, i); ok {
			opts[i-1] = num + " " + name
		} else {
			opts[i-1] = num
		}
	}
	return opts
}
